  AND bi.child_bom_code IS NULL;

COMMENT ON COLUMN plm_product_bom_item.item_code IS 'Component Item code snapshot for ERP BOM Item.item_code mapping.';
COMMENT ON COLUMN plm_product_bom_item.item_name IS 'Component Item name snapshot for ERP BOM Item.item_name mapping.';
COMMENT ON COLUMN plm_product_bom_item.child_bom_code IS 'Child BOM code snapshot for ERP BOM Item.bom_no mapping.';

ALTER TABLE plm_product_bom_operation
