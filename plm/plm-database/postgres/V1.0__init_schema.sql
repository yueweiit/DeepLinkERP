-- YUEWEI PLM PostgreSQL schema
-- Scope: PLM only. ERP/MES/WMS/CRM are reserved as mappings/logs, not implemented as formal integrations.

CREATE SCHEMA IF NOT EXISTS plm;
SET search_path TO plm;

CREATE DOMAIN bool_flag AS smallint
  CHECK (VALUE IN (0, 1));

CREATE DOMAIN rate_decimal AS numeric(10,4)
  CHECK (VALUE IS NULL OR VALUE >= 0);

CREATE DOMAIN amount_decimal AS numeric(18,4)
  CHECK (VALUE IS NULL OR VALUE >= 0);

CREATE TABLE plm_customer (
  customer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_code varchar(64) NOT NULL,
  customer_name varchar(255) NOT NULL,
  customer_short_name varchar(128),
  customer_type varchar(64),
  country_code varchar(32),
  contact_name varchar(128),
  contact_phone varchar(64),
  contact_email varchar(128),
  status varchar(32) NOT NULL DEFAULT 'draft',
  remark text,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_by varchar(64) NOT NULL,
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_by varchar(64) NOT NULL,
  deleted_flag bool_flag NOT NULL DEFAULT 0,
  CONSTRAINT uk_plm_customer_code UNIQUE (customer_code),
  CONSTRAINT ck_plm_customer_status CHECK (status IN ('draft', 'active', 'inactive'))
);

CREATE TABLE sys_user (
  user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_code varchar(64) NOT NULL,
  user_name varchar(128) NOT NULL,
