CREATE TABLE plm_product (
  product_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_product_id bigint REFERENCES plm_product(product_id),
  customer_id bigint REFERENCES plm_customer(customer_id),
  product_code varchar(64) NOT NULL,
  product_name varchar(255) NOT NULL,
  product_type varchar(64) NOT NULL,
  series_name varchar(128),
  model varchar(128),
  color varchar(64),
  material varchar(128),
  package_type varchar(128),
  surface_process varchar(128),
  core_process varchar(255),
  composition text,
  owner_user_id bigint REFERENCES sys_user(user_id),
  version_no varchar(32) NOT NULL,
  status varchar(32) NOT NULL DEFAULT 'draft',
  effective_date date,
  released_at timestamp,
  released_by varchar(64),
  remark text,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_by varchar(64) NOT NULL,
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_by varchar(64) NOT NULL,
  deleted_flag bool_flag NOT NULL DEFAULT 0,
  CONSTRAINT uk_plm_product_code UNIQUE (product_code),
  CONSTRAINT ck_plm_product_type CHECK (product_type IN ('product_line', 'model_variant')),
