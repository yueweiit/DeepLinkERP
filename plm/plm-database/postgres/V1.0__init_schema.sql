  role_permission_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_id bigint NOT NULL REFERENCES sys_role(role_id),
  permission_id bigint NOT NULL REFERENCES sys_permission(permission_id),
