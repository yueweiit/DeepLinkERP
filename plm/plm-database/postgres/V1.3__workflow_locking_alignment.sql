-- 2. Model variant projects may repeat the same phone model under one parent.
-- DingTalk approval instance id is the idempotency key for connector intake.

-- 3. Tooling/fixture and workstation traceability.
ALTER TABLE plm_inventory
  ADD COLUMN IF NOT EXISTS current_workstation_id bigint REFERENCES plm_workstation(workstation_id),
  ADD COLUMN IF NOT EXISTS tooling_owner_user_id bigint REFERENCES sys_user(user_id),
  ADD COLUMN IF NOT EXISTS tooling_owner_user_name varchar(128);

CREATE TABLE IF NOT EXISTS plm_inventory_workstation_binding (
  inventory_workstation_binding_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  inventory_id bigint NOT NULL REFERENCES plm_inventory(inventory_id),
  workstation_id bigint NOT NULL REFERENCES plm_workstation(workstation_id),
  bind_type varchar(32) NOT NULL DEFAULT 'install',
  bind_status varchar(32) NOT NULL DEFAULT 'active',
  installed_at timestamp,
  removed_at timestamp,
  remark text,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_by varchar(64) NOT NULL,
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_by varchar(64) NOT NULL,
  deleted_flag bool_flag NOT NULL DEFAULT 0,
  CONSTRAINT ck_plm_inventory_workstation_binding_type CHECK (bind_type IN ('install', 'assignment', 'maintenance')),
  CONSTRAINT ck_plm_inventory_workstation_binding_status CHECK (bind_status IN ('active', 'inactive', 'removed')),
  CONSTRAINT ck_plm_inventory_workstation_binding_time CHECK (removed_at IS NULL OR installed_at IS NULL OR removed_at >= installed_at)
);

CREATE INDEX IF NOT EXISTS idx_plm_inventory_binding_inventory
ON plm_inventory_workstation_binding(inventory_id, bind_status);

CREATE INDEX IF NOT EXISTS idx_plm_inventory_binding_workstation
ON plm_inventory_workstation_binding(workstation_id, bind_status);

